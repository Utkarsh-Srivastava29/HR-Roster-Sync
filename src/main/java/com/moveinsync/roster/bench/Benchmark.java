package com.moveinsync.roster.bench;

import com.moveinsync.roster.core.booking.DeactivationSideEffects;
import com.moveinsync.roster.core.outbox.InProcessEventBus;
import com.moveinsync.roster.core.outbox.OutboxRelay;
import com.moveinsync.roster.core.reconcile.SafetyBrake;
import com.moveinsync.roster.core.validation.RawHrRecord;
import com.moveinsync.roster.persistence.memory.InMemoryRunStore;
import com.moveinsync.roster.persistence.memory.InMemoryStore;
import com.moveinsync.roster.service.CatalogService;
import com.moveinsync.roster.service.InMemoryRosterMetrics;
import com.moveinsync.roster.service.ReconciliationService;
import com.moveinsync.roster.service.RosterService;
import com.moveinsync.roster.service.model.ReconciliationRun;

import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Clock;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;

/**
 * Reproducible benchmark: {@code ./scripts/benchmark.sh} (writes docs/benchmark-results.md).
 * Uses the in-memory store so it measures our code, not a database.
 */
public final class Benchmark {

    static final String T = "acme";
    static final int N = 200_000;
    static final Instant V1 = Instant.parse("2026-10-29T10:00:00Z");
    static final Instant TAKEN = Instant.parse("2026-10-30T23:00:00Z");

    private final StringBuilder out = new StringBuilder();

    public static void main(String[] args) throws Exception {
        Benchmark b = new Benchmark();
        b.run();
        System.out.println(b.out);
        if (args.length > 0) Files.writeString(Path.of(args[0]), b.out.toString());
    }

    private void line(String s) { out.append(s).append('\n'); }

    void run() throws Exception {
        Path tmp = Files.createTempDirectory("roster-bench");
        line("# Benchmark results");
        line("");
        line("Generated by `com.moveinsync.roster.bench.Benchmark` (`scripts/benchmark.sh`). In-memory store, so the numbers are our code, not a database.");
        line("");
        line("**Machine:** " + machine());
        line("");

        InMemoryStore store = new InMemoryStore();
        Clock clock = Clock.systemUTC();
        InMemoryRosterMetrics metrics = new InMemoryRosterMetrics();
        CatalogService catalogs = new CatalogService(store);
        catalogs.put(T, SyntheticRoster.OFFICES, SyntheticRoster.SHIFTS);
        RosterService roster = new RosterService(store, catalogs, metrics, clock);

        // ---------------- 1. live feed throughput (batches through the full validation + transaction path)
        int threads = 8, batch = 1_000;
        List<List<RawHrRecord>> batches = new ArrayList<>();
        for (int s = 0; s < N; s += batch) {
            List<RawHrRecord> b = new ArrayList<>(batch);
            for (int i = s; i < Math.min(N, s + batch); i++) {
                var p = SyntheticRoster.profile(i, 0);
                b.add(new RawHrRecord("CREATE", SyntheticRoster.id(i), "1", V1.toString(), p.name(), p.email(), p.phone(),
                        p.managerId(), p.officeCode(), p.shiftCode(), null, null));
            }
            batches.add(b);
        }
        ExecutorService pool = Executors.newFixedThreadPool(threads);
        List<Long> batchMs = Collections.synchronizedList(new ArrayList<>());
        long t0 = System.nanoTime();
        List<Future<?>> fs = new ArrayList<>();
        for (List<RawHrRecord> b : batches) fs.add(pool.submit(() -> {
            long s = System.nanoTime();
            roster.ingestBatch(T, b);
            batchMs.add((System.nanoTime() - s) / 1_000_000);
        }));
        for (Future<?> f : fs) f.get();
        double secs = (System.nanoTime() - t0) / 1e9;
        List<Long> rec = metrics.latenciesMicros();
        line("## 1. Live HR feed (`POST /api/v1/hr/events` path, without HTTP)");
        line("");
        line(String.format("%,d creates in %,d batches of %,d, %d client threads.", N, batches.size(), batch, threads));
        line("");
        line("| metric | value |");
        line("|---|---|");
        line(String.format("| throughput | %,.0f records/s |", N / secs));
        line("| per record (validate + lock + decide + commit + outbox) p50 / p99 | " + pct(rec, 50) + " / " + pct(rec, 99) + " us |");
        line("| per 1,000-record batch p50 / p99 | " + pct(batchMs, 50) + " / " + pct(batchMs, 99) + " ms |");

        // replay the whole feed: every record must be a duplicate, nothing changes
        int eventsBefore = store.allOutboxEvents().size();
        long r0 = System.nanoTime();
        long dups = 0;
        for (List<RawHrRecord> b : batches) dups += roster.ingestBatch(T, b).totals().getOrDefault("DUPLICATE", 0);
        line(String.format("| replay of the same %,d records | %,d duplicates, %d new change events, %.1f s |",
                N, dups, store.allOutboxEvents().size() - eventsBefore, (System.nanoTime() - r0) / 1e9));
        line("");

        // ---------------- 2. outbox relay
        InProcessEventBus bus = new InProcessEventBus().subscribe(new DeactivationSideEffects(store, clock));
        OutboxRelay relay = new OutboxRelay(store, bus, clock, OutboxRelay.Listener.NONE, OutboxRelay.Hooks.NONE);
        long backlog = store.unpublishedCount();
        long p0 = System.nanoTime();
        relay.drainAll(1_000);
        double ps = (System.nanoTime() - p0) / 1e9;
        line("## 2. Outbox relay");
        line("");
        line(String.format("Drained a backlog of %,d change events in %.2f s (%,.0f events/s) to an in-process bus with the booking consumer.",
                backlog, ps, backlog / ps));
        line("");

        // ---------------- 3. nightly diff of 200,000 rows
        ReconciliationService recon = new ReconciliationService(store, roster, catalogs, new InMemoryRunStore(), metrics, clock,
                tmp, SafetyBrake.defaults());
        line("## 3. Nightly reconciliation of a 200,000-row export");
        line("");
        line("| scenario | diff time | total incl. apply | buckets opened / 4,096 | max rows in memory | result |");
        line("|---|---|---|---|---|---|");

        reconcile(recon, tmp, "identical file", SyntheticRoster.rows(0, N, 1, V1, 0), N, true);
        reconcile(recon, tmp, "file cut off at 120,000 of 200,000 rows (no trailer)", SyntheticRoster.rows(0, N, 1, V1, 0), 120_000, false);

        List<SyntheticRoster.Row> changed = new ArrayList<>(SyntheticRoster.rows(0, N - 2_000, 1, V1, 0));   // 1% missing
        for (int i = 0; i < 2_000; i++) {                                                                    // 1% changed
            int k = i * 97;
            changed.set(k, new SyntheticRoster.Row(SyntheticRoster.id(k), 2, V1, SyntheticRoster.profile(k, 1)));
        }
        changed.addAll(SyntheticRoster.rows(N, N + 1_000, 1, V1, 0));                                       // 0.5% new
        reconcile(recon, tmp, "1% changed, 0.5% new, 1% missing", changed, changed.size(), true);

        line("");
        line("\"Max rows in memory\" is the largest number of rows the diff held at once (file rows + store rows of the buckets "
                + "being compared in one partition). The 200,000-row file itself is only ever streamed.");
        line("");
        line(String.format("The whole benchmark - including the in-memory store of %,d employees and %,d outbox events in the same heap - runs with `-Xmx%dm`.",
                N + 1_000, store.allOutboxEvents().size(), Runtime.getRuntime().maxMemory() / (1024 * 1024)));
        recon.close();
        pool.shutdown();
    }

    private void reconcile(ReconciliationService recon, Path tmp, String label, List<SyntheticRoster.Row> rows, int limit,
                           boolean trailer) throws Exception {
        Path f = tmp.resolve("export.csv");
        SyntheticRoster.writeExport(f, rows, TAKEN, limit, trailer);
        long t0 = System.nanoTime();
        ReconciliationRun r;
        try (InputStream in = Files.newInputStream(f)) {
            r = recon.submit(T, in);
        }
        recon.awaitIdle(T, 600_000);
        long total = (System.nanoTime() - t0) / 1_000_000;
        r = recon.get(T, r.runId());
        String result = r.status() == ReconciliationRun.Status.BRAKED
                ? "**BRAKED** - appears to be missing " + String.format("%,d", r.brake().appearsMissing()) + " records; nothing applied"
                : r.status() + " " + r.applied();
        line("| " + label + " | " + r.stats().diffMillis() + " ms | " + total + " ms | " + r.stats().bucketsOpened()
                + " | " + String.format("%,d", r.stats().maxRowsInMemory()) + " | " + result + " |");
    }

    static long pct(List<Long> xs, int p) {
        List<Long> s = new ArrayList<>(xs);
        Collections.sort(s);
        if (s.isEmpty()) return 0;
        return s.get(Math.max(0, Math.min(s.size() - 1, (int) Math.ceil(p / 100.0 * s.size()) - 1)));
    }

    private static String machine() {
        String cpu = "unknown CPU";
        try {
            for (String l : Files.readAllLines(Path.of("/proc/cpuinfo")))
                if (l.startsWith("model name")) { cpu = l.substring(l.indexOf(':') + 1).trim(); break; }
        } catch (Exception ignored) { }
        Runtime rt = Runtime.getRuntime();
        return cpu + ", " + rt.availableProcessors() + " vCPU, JVM max heap " + rt.maxMemory() / (1024 * 1024) + " MB, "
                + System.getProperty("java.vm.name") + " " + System.getProperty("java.version") + ", "
                + System.getProperty("os.name") + " " + System.getProperty("os.arch");
    }
}
